import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";
const require = createRequire(import.meta.url);
const { createClient } = require(resolve(import.meta.dirname, "..", "apps/web/node_modules/@supabase/supabase-js"));
const root = resolve(import.meta.dirname, "..");
if (!process.env.RUNTIME_FIXTURES_OUTPUT) throw new Error("RUNTIME_FIXTURES_OUTPUT is required; full runtime never falls back to SKIP");
const contract = JSON.parse(readFileSync(process.env.RUNTIME_FIXTURES_OUTPUT, "utf8"));
if (contract.version !== 1 || !contract.env || !contract.credentials || Object.keys(contract.credentials).length !== 10) throw new Error("Invalid full runtime fixture contract");
for (const name of ["student-minor-a", "student-adult-a", "student-school-b"]) if (!contract.ids?.[name]) throw new Error(`Full runtime fixture contract lacks expected evidence owner: ${name}`);
for (const name of ["minor", "adult", "schoolB"]) if (!contract.evidence?.[name]) throw new Error(`Full runtime fixture contract lacks expected evidence: ${name}`);
Object.assign(process.env, contract.env);
const required = ["RUNTIME_SUPABASE_URL", "RUNTIME_SUPABASE_ANON_KEY", "RUNTIME_FULL_FIXTURES_READY"];
for (const name of required) if (!process.env[name]) throw new Error(`Missing runtime full variable: ${name}`);
const structural = spawnSync(process.execPath, [resolve(root, "scripts/verify-contact-security.mjs")], { stdio: "inherit", env: process.env });
if (structural.status !== 0) throw new Error("Contact structural gate failed");
const s1 = spawnSync(process.execPath, [resolve(root, "scripts/verify-runtime-profile-boundary.mjs")], { stdio: "inherit", env: process.env });
if (s1.status !== 0) throw new Error("S1 regression gate failed");
const contact = spawnSync(process.execPath, [resolve(root, "scripts/verify-runtime-contact.mjs")], { stdio: "inherit", env: process.env });
if (contact.status !== 0) throw new Error("Contact matrix failed");
const opportunities = spawnSync(process.execPath, [resolve(root, "scripts/verify-runtime-opportunities.mjs")], { stdio: "inherit", env: process.env });
if (opportunities.status !== 0) throw new Error("Core opportunity visibility/ownership gate failed");
const db = createClient(process.env.RUNTIME_SUPABASE_URL, process.env.RUNTIME_SUPABASE_ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const actor = (name) => {
  const credentials = contract.credentials[name];
  if (!credentials?.email || !credentials?.password || !contract.ids?.[name]) throw new Error(`Contract lacks complete ${name} fixture`);
  return { ...credentials, id: contract.ids[name] };
};
const login = async (name) => {
  const fixture = actor(name);
  const { data, error } = await db.auth.signInWithPassword({ email: fixture.email, password: fixture.password });
  if (error || !data.user || data.user.id !== fixture.id) throw new Error(`Core fixture authentication failed for ${name}`);
  return { client: db, id: data.user.id };
};
const company = await login("company-a");
const student = actor("student-adult-a").id;
const application = contract.ids.adultApplicationId;
const unrelatedApplication = contract.ids.unrelatedApplicationId;
const post = contract.ids.postId;
const foreignOpportunity = contract.ids.foreignOpportunityId;
const ownOpportunity = contract.ids.ownOpportunityId;
if (!foreignOpportunity || !ownOpportunity) throw new Error("Full contract lacks opportunity ownership IDs");
const own = await company.client.from("opportunities").select("id,publisher_id,status").eq("id", ownOpportunity).single();
if (own.error || own.data?.publisher_id !== company.id || own.data?.status !== "open") throw new Error("Core owner status check failed");
const crossTenant = await company.client.from("opportunities").select("id,publisher_id,status").eq("id", foreignOpportunity).single();
if (crossTenant.error || crossTenant.data?.publisher_id === company.id || crossTenant.data?.status !== "open") throw new Error("Core public opportunity visibility check failed");
const applicationRead = await company.client.from("job_applications").select("id,opportunity_id").eq("id", application);
if (applicationRead.error || applicationRead.data?.length !== 1) throw new Error("Core application timeline visibility check failed");
const event = await company.client.from("application_events").insert({ application_id: unrelatedApplication, actor_id: company.id, event_type: "note", note: "spoof" });
if (!event.error) throw new Error("Core spoofing negative failed: forged application_events.actor_id was accepted");
const profile = await company.client.from("profiles").update({ account_type: "company" }).eq("id", student).select("id");
if (!profile.error && profile.data?.length) throw new Error("Core spoofing negative failed: cross-profile mutation was accepted");
const view = await company.client.from("profile_views").insert({ viewer_id: student, viewed_id: company.id });
if (!view.error) throw new Error("Core spoofing negative failed: forged profile_views.viewer_id was accepted");
const comment = await company.client.from("post_comments").insert({ post_id: post, author_id: student, content: "spoof" });
if (!comment.error) throw new Error("Core spoofing negative failed: forged post_comments.author_id was accepted");
const studentClient = await login("student-adult-a");
const foreignView = await studentClient.client.from("profile_views").insert({ viewer_id: company.id, viewed_id: student });
if (!foreignView.error) throw new Error("Core spoofing negative failed: foreign viewer_id was accepted");
const foreignComment = await studentClient.client.from("post_comments").insert({ post_id: post, author_id: company.id, content: "spoof" });
if (!foreignComment.error) throw new Error("Core spoofing negative failed: foreign author_id was accepted");
console.log("verify:runtime-full passed S1 regression, Contact matrix, Core authorization and three spoofing negatives.");
